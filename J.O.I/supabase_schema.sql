CREATE OR REPLACE FUNCTION public.joi_sync_identity_sequences()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  identity_column record;
  sequence_name text;
  maximum_id bigint;
BEGIN
  FOR identity_column IN
    SELECT table_name, column_name
    FROM information_schema.columns
    WHERE table_schema = 'public'
      AND is_identity = 'YES'
      AND table_name IN (
        'tblCourseList', 'tblStudentInformation', 'tblLINKStudent_Course',
        'tblEmpJobPosition', 'tblEmployees', 'tblContactType', 'tblContacts',
        'tblSubjectSections', 'tblStudentSubjectLoad', 'tblAdmissionDocuments',
        'tblPayments', 'tblPromissoryNotes', 'tblDatabaseBackups',
        'tblStudentAssessment'
      )
  LOOP
    EXECUTE format(
      'SELECT COALESCE(MAX(%I), 0) FROM public.%I',
      identity_column.column_name,
      identity_column.table_name
    ) INTO maximum_id;

    sequence_name := pg_get_serial_sequence(
      format('%I.%I', 'public', identity_column.table_name),
      identity_column.column_name
    );

    IF sequence_name IS NOT NULL THEN
      IF maximum_id = 0 THEN
        PERFORM setval(sequence_name, 1, false);
      ELSE
        PERFORM setval(sequence_name, maximum_id, true);
      END IF;
    END IF;
  END LOOP;
END;
$$;

REVOKE ALL ON FUNCTION public.joi_sync_identity_sequences() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.joi_sync_identity_sequences() TO service_role;
