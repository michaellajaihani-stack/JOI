CREATE OR REPLACE FUNCTION public.joi_enroll_subject(p_student_id bigint, p_section_id bigint)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_student public."tblStudentInformation"%ROWTYPE;
  v_section public."tblSubjectSections"%ROWTYPE;
  v_units integer;
  v_gross numeric(12,2);
  v_paid numeric(12,2);
BEGIN
  SELECT * INTO v_student
  FROM public."tblStudentInformation"
  WHERE "lngStudentID" = p_student_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'Student not found.';
  END IF;

  SELECT * INTO v_section
  FROM public."tblSubjectSections"
  WHERE "lngSectionID" = p_section_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'Subject section not found.';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM public."tblStudentSubjectLoad" l
    JOIN public."tblSubjectSections" s ON s."lngSectionID" = l."lngSectionID"
    WHERE l."lngStudentID" = p_student_id
      AND l."strTerm" = v_student."strSemester"
      AND s."strSubjectCode" = v_section."strSubjectCode"
  ) THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'You already have this subject in your current load.';
  END IF;

  IF v_section."strPrerequisiteCode" IS NOT NULL
     AND v_section."strPrerequisiteCode" <> 'NONE'
     AND v_student."ysnHasINC" = 1
     AND position(v_section."strPrerequisiteCode" in COALESCE(v_student."strINCSubject", '')) > 0 THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'Prerequisite blocked by an unresolved INC.';
  END IF;

  SELECT COALESCE(SUM(s."intUnits"), 0)::integer INTO v_units
  FROM public."tblStudentSubjectLoad" l
  JOIN public."tblSubjectSections" s ON s."lngSectionID" = l."lngSectionID"
  WHERE l."lngStudentID" = p_student_id
    AND l."strTerm" = v_student."strSemester";

  IF v_units + v_section."intUnits" > 24 THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'Adding this section exceeds the 24-unit limit.';
  END IF;

  IF v_section."intEnrolledCount" >= v_section."intMaxCapacity" THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'Section is full.';
  END IF;

  INSERT INTO public."tblStudentSubjectLoad"
    ("lngStudentID", "lngSectionID", "strTerm", "strStatus", "strGrade")
  VALUES (
    p_student_id,
    p_section_id,
    v_student."strSemester",
    CASE WHEN v_student."ysnHasINC" = 1 THEN 'Conditional (INC Grace Period)' ELSE 'Pre-Registered' END,
    'In Progress'
  );

  UPDATE public."tblSubjectSections"
  SET "intEnrolledCount" = "intEnrolledCount" + 1
  WHERE "lngSectionID" = p_section_id;

  SELECT COALESCE(
    SUM(s."intUnits" * s."curPerUnitFee" + s."curLabFee") + COALESCE(v_student."curMiscFee", 6850),
    29050
  )::numeric(12,2)
  INTO v_gross
  FROM public."tblStudentSubjectLoad" l
  JOIN public."tblSubjectSections" s ON s."lngSectionID" = l."lngSectionID"
  WHERE l."lngStudentID" = p_student_id
    AND l."strTerm" = v_student."strSemester";

  SELECT COALESCE(SUM(p."curAmount"), 0)::numeric(12,2) INTO v_paid
  FROM public."tblPayments" p
  WHERE p."lngStudentID" = p_student_id
    AND p."strStatus" = 'Paid / Verified';

  UPDATE public."tblStudentInformation"
  SET "curOutstandingBalance" = GREATEST(0, v_gross - v_paid),
      "dtmLastChanged" = now()
  WHERE "lngStudentID" = p_student_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.joi_drop_subject(p_student_id bigint, p_load_id bigint)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_student public."tblStudentInformation"%ROWTYPE;
  v_load public."tblStudentSubjectLoad"%ROWTYPE;
  v_gross numeric(12,2);
  v_paid numeric(12,2);
BEGIN
  SELECT * INTO v_student
  FROM public."tblStudentInformation"
  WHERE "lngStudentID" = p_student_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'Student not found.';
  END IF;

  SELECT * INTO v_load
  FROM public."tblStudentSubjectLoad"
  WHERE "lngLoadID" = p_load_id AND "lngStudentID" = p_student_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'Subject load entry not found.';
  END IF;

  DELETE FROM public."tblStudentSubjectLoad"
  WHERE "lngLoadID" = p_load_id;

  UPDATE public."tblSubjectSections"
  SET "intEnrolledCount" = GREATEST(0, "intEnrolledCount" - 1)
  WHERE "lngSectionID" = v_load."lngSectionID";

  SELECT COALESCE(
    SUM(s."intUnits" * s."curPerUnitFee" + s."curLabFee") + COALESCE(v_student."curMiscFee", 6850),
    29050
  )::numeric(12,2)
  INTO v_gross
  FROM public."tblStudentSubjectLoad" l
  JOIN public."tblSubjectSections" s ON s."lngSectionID" = l."lngSectionID"
  WHERE l."lngStudentID" = p_student_id
    AND l."strTerm" = v_student."strSemester";

  SELECT COALESCE(SUM(p."curAmount"), 0)::numeric(12,2) INTO v_paid
  FROM public."tblPayments" p
  WHERE p."lngStudentID" = p_student_id
    AND p."strStatus" = 'Paid / Verified';

  UPDATE public."tblStudentInformation"
  SET "curOutstandingBalance" = GREATEST(0, v_gross - v_paid),
      "dtmLastChanged" = now()
  WHERE "lngStudentID" = p_student_id;
END;
$$;

