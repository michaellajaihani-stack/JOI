-- J.O.I Academy schema for Supabase (PostgreSQL).
-- Run in the Supabase SQL Editor on a new project.
--
-- Authentication:
--   Create accounts with Supabase Auth, then set authUserId on the matching
--   student/employee row. Never store passwords in these public tables.
--   Keep the service-role key on the server only; never put it in the browser.
--
-- Security:
--   RLS is enabled on every table, with no public/anon policies.
--   Add narrowly scoped policies only if clients will access tables directly.
--   A trusted server using the service-role key can access these tables.
--
-- Migration note:
--   This schema does not copy data from the local SQLite database. Use the
--   one-time migration script after this schema has been installed.

